"""Autonomous, AI-Powered Comment Reply Engine for The Secret Place.

Monitors incoming YouTube comments across channel uploads, classifies intent
(prayer request, Amen affirmation, sleep/peace testimony, theological inquiry,
or spam/scam), drafts context-aware, personalized pastoral replies using
Google Gemini Brain, and safely posts them via the YouTube Data API v3 while
enforcing strict anti-spam, anti-shadowban, and $0.00 quota safety invariants.

Invariants Enforced:
1. Hard Cost Lock: $0.00 / month forever (free YouTube Data API & Gemini Free Tier).
2. Persona Integrity: Reverent, sacred editorial voice of The Secret Place. Zero
   mentions of John Azani or Azani John. No financial solicitation or links.
3. Anti-Spam / Shadowban Defense: Every reply is uniquely generated by Gemini;
   never post identical boilerplate text. Randomized human jitter pacing (4–10s).
4. Crisis Safety: Immediate compassion and 988/111 lifeline info on self-harm.
5. Scam Immunity: Automatic regex and keyword filtering for WhatsApp/crypto scammers.
"""
